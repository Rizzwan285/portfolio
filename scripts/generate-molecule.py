"""Regenerate src/lib/molecule.data.ts — the 3D molecule in the hero.

Usage (needs Python 3 with RDKit and NumPy):
    pip install rdkit numpy
    python scripts/generate-molecule.py src/lib/molecule.data.ts

To show a different molecule, change SMILES and NAME below. The script
embeds 60 conformers, keeps those within 6 kcal/mol of the lowest energy,
and picks the most compact one so it reads well when rotated.
"""
import json
import sys

import numpy as np
from rdkit import Chem
from rdkit.Chem import AllChem, Descriptors, rdMolDescriptors

NAME = "Imatinib"
SMILES = "Cc1ccc(NC(=O)c2ccc(CN3CCN(C)CC3)cc2)cc1Nc1nccc(-c2cccnc2)n1"

mol = Chem.AddHs(Chem.MolFromSmiles(SMILES))
params = AllChem.ETKDGv3()
params.randomSeed = 7
conf_ids = list(AllChem.EmbedMultipleConfs(mol, numConfs=60, params=params))
energies = [e for (_, e) in AllChem.MMFFOptimizeMoleculeConfs(mol, maxIters=2000)]
heavy = Chem.RemoveHs(mol)


def positions(cid):
    c = heavy.GetConformer(cid)
    p = np.array([list(c.GetAtomPosition(i)) for i in range(heavy.GetNumAtoms())])
    return p - p.mean(axis=0)


def compactness(cid):
    s = np.linalg.svd(positions(cid), compute_uv=False)
    return s[1] / s[0]


e_min = min(energies)
best = max((cid for cid, e in zip(conf_ids, energies) if e - e_min < 6.0), key=compactness)

pos = positions(best)
_, _, vt = np.linalg.svd(pos, full_matrices=False)
pos = pos @ vt.T  # longest axis along x
pos /= np.abs(pos).max()

elements = sorted({a.GetSymbol() for a in heavy.GetAtoms()})
atoms = [{"e": a.GetSymbol(), "p": [round(float(v), 4) for v in pos[a.GetIdx()]]} for a in heavy.GetAtoms()]
bonds = [
    [b.GetBeginAtomIdx(), b.GetEndAtomIdx(), 1.5 if b.GetIsAromatic() else b.GetBondTypeAsDouble()]
    for b in heavy.GetBonds()
]
plain = Chem.MolFromSmiles(SMILES)

with open(sys.argv[1], "w") as fh:
    fh.write("// Generated by scripts/generate-molecule.py (RDKit ETKDGv3 + MMFF) — heavy atoms only,\n")
    fh.write("// centred and scaled to unit radius. Regenerate rather than hand-edit.\n")
    fh.write(f"// SMILES: {SMILES}\n\n")
    fh.write(f"export type Element = {' | '.join(repr(e) for e in elements)};\n")
    fh.write("export interface MoleculeAtom { e: Element; p: [number, number, number] }\n")
    fh.write("export type MoleculeBond = [from: number, to: number, order: number];\n\n")
    fh.write("export const molecule = {\n")
    fh.write(f"  name: '{NAME}',\n")
    fh.write(f"  formula: '{rdMolDescriptors.CalcMolFormula(plain)}',\n")
    fh.write(f"  weight: {Descriptors.MolWt(plain):.2f},\n")
    fh.write("  atoms: " + json.dumps(atoms, separators=(",", ":")) + " as MoleculeAtom[],\n")
    fh.write("  bonds: " + json.dumps(bonds, separators=(",", ":")) + " as MoleculeBond[],\n")
    fh.write("};\n")

print(f"{NAME}: {len(atoms)} atoms, {len(bonds)} bonds, elements {elements}")
